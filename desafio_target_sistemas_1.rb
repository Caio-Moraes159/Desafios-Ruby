dados = JSON.parse(json_data)
comissoes = Hash.new(0.0)

dados["vendas"].each do |venda|
  vendedor = venda["vendedor"]
  valor = venda["valor"]
  comissao = 0.0

  if valor < 100.00
    comissao = 0.0
  elsif valor < 500.00
    comissao = valor * 0.01
  else
    comissao = valor * 0.05
  end

  comissoes[vendedor] += comissao
end

